package io.github.prostagma1.razlom.game

/**
 * Реликвия — постоянный эффект на весь забег. В отличие от наград вроде
 * «+2 к атаке» реликвии меняют сами правила, поэтому из них и складывается билд.
 */
enum class Relic(val title: String, val description: String, val price: Int) {
    TALISMAN("Ржавый оберег", "Первый павший союзник в бою поднимается с 1 HP", 70),
    WAR_STONE("Точильный камень войны", "+3 к урону в первом раунде боя", 55),
    BANDAGES("Походные бинты", "После победы отряд лечится на 6", 50),
    BOOTS("Сапоги гонца", "+1 шаг всем бойцам", 65),
    VIALS("Ядовитые склянки", "Атаки с дальностью 3 и дальше отравляют цель на 2 хода", 60),
    STONE_SKIN("Каменная кожа", "Отряд начинает бой со щитом 5", 60),
    COIN("Кровавая монета", "+8 золота за каждый бой", 45),
    FURY("Тотем ярости", "Смерть союзника даёт остальным +3 к урону до конца боя", 55),
    BANNER("Знамя знахаря", "Любое лечение сильнее в полтора раза", 50);

    companion object {
        fun byName(name: String): Relic? = entries.firstOrNull { it.name == name }
    }
}
